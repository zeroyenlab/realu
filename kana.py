# -*- coding: utf-8 -*-
"""★★★五十音を座標にする ── ★日本語にしかない構造を、そのまま部品にする。

★★なぜ効くと思うか（2026-09-10 Daito の案）
  ★活用は「行を固定して、段だけ動かす」操作そのもの:
      書か / 書き / 書く / 書け / 書こ   ← か行のまま、段だけ動く
      読ま / 読み / 読む / 読め / 読も   ← ま行のまま、段だけ動く
  ★いまは この4つ5つを**バラバラの無関係なベクトル**として覚えている。
  ★★座標にすれば「未然形＝段をあに動かす」を**1回覚えれば全部の動詞に効く**。

★★安さ
  ★部品は 38 個だけ（★全体の平均19 ＋ 最後の1文字19）。
  ★38 × 幅384 = 14,592 個 ＝ ★土台の 0.11%。
  ★★行列をゼロで初期化するので、★最初は今と**完全に同じ振る舞い**。
    ★効かなければゼロのまま残るだけで、★壊れようがない。

★★先行研究
  ★韓国語はジャモ分解（対応が決定的）、★中国語は部首分解が確立している。
  ★かなも対応が決定的なので同じ手が使える。★ただし狙いが違う ──
  ★★あちらは音や意味のため。★こちらは**活用**のため。
"""
GYO = "あかさたなはまやらわ"          # ★行（子音）
DAN = "あいうえお"                    # ★段（母音）
_ROWS = {"あ":"あいうえお","か":"かきくけこ","さ":"さしすせそ","た":"たちつてと",
         "な":"なにぬねの","は":"はひふへほ","ま":"まみむめも","や":"や_ゆ_よ",
         "ら":"らりるれろ","わ":"わゐ_ゑを"}
_DAKU = {"が":"か","ぎ":"き","ぐ":"く","げ":"け","ご":"こ","ざ":"さ","じ":"し","ず":"す",
         "ぜ":"せ","ぞ":"そ","だ":"た","ぢ":"ち","づ":"つ","で":"て","ど":"と",
         "ば":"は","び":"ひ","ぶ":"ふ","べ":"へ","ぼ":"ほ","ゔ":"う"}
_HAN = {"ぱ":"は","ぴ":"ひ","ぷ":"ふ","ぺ":"へ","ぽ":"ほ"}
_SMALL = "ぁぃぅぇぉっゃゅょゎ"
# ★かな → (行の番号, 段の番号)
_POS = {}
for g, s in _ROWS.items():
    gi = GYO.index(g)
    for di, ch in enumerate(s):
        if ch != "_": _POS[ch] = (gi, di)
_POS["ん"] = (GYO.index("わ"), 4)      # ★「ん」はわ行の端に置く（★便宜）

N = 19          # ★行10 ＋ 段5 ＋ 濁2 ＋ 小1 ＋ カナ1
def kana_vec(ch):
    """★1文字 → 19次元。★かなでなければ全部0。"""
    v = [0.0]*N
    c = ch
    kata = False
    if "\u30a1" <= ch <= "\u30fa":       # ★カタカナ → ひらがなに寄せる
        c = chr(ord(ch) - 0x60); kata = True
    base, daku, han, small = c, 0.0, 0.0, 0.0
    if c in _DAKU: base, daku = _DAKU[c], 1.0
    elif c in _HAN: base, han = _HAN[c], 1.0
    if c in _SMALL:
        small = 1.0
        big = {"ぁ":"あ","ぃ":"い","ぅ":"う","ぇ":"え","ぉ":"お","っ":"つ",
               "ゃ":"や","ゅ":"ゆ","ょ":"よ","ゎ":"わ"}
        base = big.get(c, c)
    if base not in _POS: return v
    gi, di = _POS[base]
    v[gi] = 1.0; v[10+di] = 1.0
    v[15], v[16], v[17] = daku, han, small
    v[18] = 1.0 if kata else 0.0
    return v

def token_vec(s):
    """★トークン → 38次元（★全体の平均19 ＋ 最後の1文字19）。★活用は語尾に出る。"""
    vs = [kana_vec(c) for c in s if kana_vec(c) != [0.0]*N]
    if not vs: return [0.0]*(N*2)
    mean = [sum(x[i] for x in vs)/len(vs) for i in range(N)]
    return mean + vs[-1]
